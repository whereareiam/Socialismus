package me.whereareiam.socialismus.api.type.chat;

/**
 * Represents the participants involved in a message interaction within the Socialismus plugin.
 * This enum defines the roles of users in a communication exchange.
 */
public enum Participants {
	/**
	 * Represents the user who initiates or sends the message
	 */
	SENDER,

	/**
	 * Represents the user who receives the message
	 */
	RECIPIENT
}